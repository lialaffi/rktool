#' Density plot of tk and/or rk, with faceting and rhythmic reference lines
#'
#' Draws the kernel density of the intervals \code{tk}, of the rhythmic
#' ratio \code{rk}, or of both (default), as produced by
#' \code{\link{calculate_rk}}. The plot can be split in facets by any
#' column(s) of \code{data}, in particular the same ones passed to
#' \code{by} in \code{calculate_rk()} (e.g. \code{file_id}, \code{ind_id}).
#' Optionally, vertical lines mark the centers of the rhythmic categories on
#' the rk density.
#'
#' @param data A data frame, typically the output of
#'   \code{\link{calculate_rk}}.
#' @param what What to plot: \code{"both"} (default, tk and rk), \code{"rk"}
#'   or \code{"tk"}. With \code{"both"}, tk and rk are drawn in separate
#'   panels (each with its own x axis), side by side for each facet.
#' @param rk_col,tk_col Columns with rk and tk (bare or string; defaults
#'   \code{"rk"} and \code{"tk"}, the names produced by
#'   \code{calculate_rk()} / \code{calculate_tk()}). Only the one(s) needed
#'   by \code{what} are used.
#' @param facet_by Optional column(s) to facet by (bare, string or
#'   \code{c(...)}), e.g. \code{c(file_id, ind_id)}: one set of panels for
#'   each combination present in the data. If \code{NULL} (default) no
#'   faceting is done (besides the tk / rk split when \code{what = "both"}).
#' @param color_by Optional column mapped to colour/fill (bare or string),
#'   to overlay several densities in the same panel, e.g. \code{sex}. Can be
#'   combined with \code{facet_by}.
#' @param fill Logical, if \code{TRUE} (default) the area under the density
#'   is filled (semi-transparent).
#' @param peaks Optional character vector of rhythmic categories (same
#'   format as \code{\link{classify_rk}}'s \code{peaks}, e.g.
#'   \code{c("1_1", "1_2", "2_1")}). A dashed vertical line is drawn in the
#'   rk panels at the center of each category (\code{1/(n+1)} for
#'   \code{"1_n"}, \code{1 - 1/(n+1)} for \code{"n_1"}, \code{0.5} for
#'   \code{"1_1"}). Default \code{NULL}: no lines.
#' @param n_max Optional integer: draws the lines for all categories from
#'   \code{1_n_max} to \code{1_1} to \code{n_max_1} (same set generated by
#'   \code{classify_rk(n_max = )}). Ignored, with a warning, if \code{peaks}
#'   is given. Default \code{NULL}: no lines.
#' @param bw,adjust Bandwidth and bandwidth multiplier of the density
#'   estimate (defaults \code{"nrd0"} and 1).
#' @param tk_max Optional upper bound for the tk density: values of tk
#'   greater than \code{tk_max} are dropped before plotting. Useful because
#'   tk usually has a long right tail. Does not affect rk.
#' @param scales Scales of the facets (\code{"fixed"} (default),
#'   \code{"free"}, \code{"free_x"}, \code{"free_y"}). With
#'   \code{what = "both"} the x axis is always free between tk and rk
#'   panels; \code{"free"} / \code{"free_y"} additionally free the y axis.
#' @param ncol Optional number of columns of the panel layout (default 2
#'   when \code{what = "both"}, so that tk and rk of the same facet sit on
#'   the same row; otherwise chosen by \code{ggplot2}).
#' @param label_both Logical, if \code{TRUE} facet labels are shown as
#'   \code{column: value}. Default \code{FALSE}.
#'
#' @return A \code{ggplot} object (can be further modified with \code{+}).
#'
#' @details
#' \code{NA} values (e.g. the last rk of each group) are removed before
#' plotting; for tk, values \code{<= 0} are dropped too. Each density is
#' drawn only over the range of the observed values (the rk axis is
#' always shown from 0 to 1). Panels with fewer than 2 valid values cannot
#' have a density and are not drawn (\code{ggplot2} warns about them).
#'
#' @examples
#' if (requireNamespace("ggplot2", quietly = TRUE)) {
#'   y <- calculate_tk(data_rktool, onset_col = onset, by = c(file_id, ind_id))
#'   y <- calculate_rk(y, tk_col = tk, by = c(file_id, ind_id))
#'
#'   print(plot_rk_density(y, tk_max = 2))               # tk and rk
#'   print(plot_rk_density(y, what = "rk", facet_by = sex))
#'   print(plot_rk_density(y, color_by = sex, tk_max = 2))
#'
#'   # reference lines of the rhythmic categories
#'   print(plot_rk_density(y, what = "rk", n_max = 5))
#'   print(plot_rk_density(y, what = "rk", peaks = c("1_1", "1_2", "2_1"),
#'                         facet_by = ind_id))
#' }
#'
#' @export
plot_rk_density <- function(data, what = c("both", "rk", "tk"),
                            rk_col = "rk", tk_col = "tk",
                            facet_by = NULL, color_by = NULL, fill = TRUE,
                            peaks = NULL, n_max = NULL,
                            bw = "nrd0", adjust = 1, tk_max = NULL,
                            scales = "fixed", ncol = NULL, label_both = FALSE) {
  what <- match.arg(what)
  if (!requireNamespace("ggplot2", quietly = TRUE)) {
    stop("plot_rk_density() requires the 'ggplot2' package to be installed.")
  }
  stopifnot(is.data.frame(data))

  vars <- if (what == "both") c("tk", "rk") else what

  # --- columns -----------------------------------------------------------
  rk_name <- if ("rk" %in% vars) .rk_select(rlang::enquo(rk_col), data, "rk_col", one = TRUE, numeric = TRUE)
  tk_name <- if ("tk" %in% vars) .rk_select(rlang::enquo(tk_col), data, "tk_col", one = TRUE, numeric = TRUE)

  facet_cols <- .rk_select(rlang::enquo(facet_by), data, "facet_by")
  color_cols <- .rk_select(rlang::enquo(color_by), data, "color_by")
  if (length(color_cols) > 1) stop("'color_by' must select at most one column.")
  
  if (any(c("variable", "value") %in% c(facet_cols, color_cols))) {
    stop("'facet_by' / 'color_by' cannot use columns named 'variable' or 'value' (reserved).")
  }
  
  # --- long data: one block per variable ---------------------------------
  extra <- unique(c(facet_cols, color_cols))
  block <- function(var, col) {
    x <- data[[col]]
    keep <- is.finite(x)
    if (var == "tk") {
      keep <- keep & x > 0
      if (!is.null(tk_max)) keep <- keep & x <= tk_max
    }
    if (!any(keep)) return(NULL)
    out <- data[keep, extra, drop = FALSE]
    out$value <- x[keep]
    out$variable <- var
    out
  }
  blocks <- list()
  if ("tk" %in% vars) blocks$tk <- block("tk", tk_name)
  if ("rk" %in% vars) blocks$rk <- block("rk", rk_name)
  df <- do.call(rbind, blocks)
  if (is.null(df) || nrow(df) == 0) stop("No valid values left to plot.")
  df$variable <- factor(df$variable, levels = vars)
  if (length(color_cols) == 1) df[[color_cols]] <- factor(df[[color_cols]])
  
  # --- density layer -----------------------------------------------------
  aes_args <- list(x = rlang::expr(.data$value))
  if (length(color_cols) == 1) {
    aes_args$colour <- rlang::sym(color_cols)
    aes_args$fill <- rlang::sym(color_cols)
  }
  p <- ggplot2::ggplot(df, do.call(ggplot2::aes, aes_args))
  
  dens_args <- list(bw = bw, adjust = adjust, trim = TRUE)
  if (fill) {
    dens_args$alpha <- 0.3
    if (length(color_cols) == 0) dens_args$fill <- "grey60"
  } else {
    dens_args$fill <- NA
  }
  p <- p + do.call(ggplot2::geom_density, dens_args)
  
  # --- rk: fixed 0-1 axis and reference lines ------------------------------
  if ("rk" %in% vars) {
    p <- p + ggplot2::geom_blank(
      data = data.frame(value = c(0, 1), variable = factor("rk", levels = vars)),
      inherit.aes = FALSE, ggplot2::aes(x = .data$value)
    )
    
    if (!is.null(peaks) && !is.null(n_max)) {
      warning("'n_max' is ignored when 'peaks' is supplied.")
      n_max <- NULL
    }
    if (!is.null(peaks) || !is.null(n_max)) {
      peaks <- .rk_peaks(peaks, n_max)
      centers <- vapply(peaks, function(pk) {
        pp <- .parse_rk_peak(pk)
        switch(pp$side,
               center = 0.5,
               left   = 1 / (pp$n + 1),
               right  = 1 - 1 / (pp$n + 1)
        )
      }, numeric(1))
      # data frame with variable = "rk": the lines appear only in rk panels
      vl <- data.frame(xintercept = unname(centers),
                       variable = factor("rk", levels = vars))
      p <- p + ggplot2::geom_vline(
        data = vl, ggplot2::aes(xintercept = .data$xintercept),
        inherit.aes = FALSE, linetype = "dashed", colour = "red", alpha = 0.6
      )
    }
  } else if (!is.null(peaks) || !is.null(n_max)) {
    warning("'peaks' / 'n_max' are ignored when what = \"tk\".")
  }
  
  # --- facets ------------------------------------------------------------
  facet_vars <- c(facet_cols, if (what == "both") "variable")
  if (length(facet_vars) > 0) {
    sc <- scales
    if (what == "both") {
      sc <- if (scales %in% c("free", "free_y")) "free" else "free_x"
      if (is.null(ncol)) ncol <- 2
    }
    p <- p + ggplot2::facet_wrap(
      ggplot2::vars(!!!rlang::syms(facet_vars)),
      scales = sc, ncol = ncol,
      labeller = if (label_both) ggplot2::label_both else ggplot2::label_value
    )
  }
  
  p +
    ggplot2::labs(x = if (what == "both") NULL else what, y = "density") +
    ggplot2::theme_bw()
}